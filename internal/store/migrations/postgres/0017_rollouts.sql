-- Rolling updates: one package job type over many hosts in stages (an
-- optional canary first, then batches or groups), stopped automatically
-- when too many fail. status: running, paused, completed, failed, cancelled.
CREATE TABLE rollouts (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  TEXT NOT NULL,
    job_type              TEXT NOT NULL,
    packages              TEXT NOT NULL DEFAULT '[]',
    status                TEXT NOT NULL,
    stages                BIGINT NOT NULL,
    current_stage         BIGINT NOT NULL DEFAULT 0,
    canary                BIGINT NOT NULL DEFAULT 0,
    max_parallel          BIGINT NOT NULL,
    wait_minutes          BIGINT NOT NULL DEFAULT 0,
    max_failure_pct       BIGINT NOT NULL DEFAULT 0,
    require_health        BIGINT NOT NULL DEFAULT 1,
    pause_after_canary    BIGINT NOT NULL DEFAULT 0,
    job_timeout_minutes   BIGINT NOT NULL DEFAULT 120,
    stage_finished_at     BIGINT NOT NULL DEFAULT 0,
    -- failures (and finished hosts) already accepted by resuming after a stop
    accepted_failures     BIGINT NOT NULL DEFAULT 0,
    accepted_processed    BIGINT NOT NULL DEFAULT 0,
    reason                TEXT NOT NULL DEFAULT '',
    created_by            BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE,
    created_at            BIGINT NOT NULL,
    finished_at           BIGINT NOT NULL DEFAULT 0
);

-- Hosts of a rollout with their stage and order; status: pending, queued,
-- succeeded, failed, skipped.
CREATE TABLE rollout_hosts (
    rollout_id BIGINT NOT NULL REFERENCES rollouts(id) ON DELETE CASCADE DEFERRABLE,
    host_id    BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    stage      BIGINT NOT NULL,
    position   BIGINT NOT NULL,
    job_id     BIGINT NOT NULL DEFAULT 0,
    status     TEXT NOT NULL DEFAULT 'pending',
    note       TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (rollout_id, host_id)
);
CREATE INDEX rollout_hosts_stage ON rollout_hosts(rollout_id, stage, position);
