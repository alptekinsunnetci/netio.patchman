-- Health check definitions. scope: 'all' hosts, one 'group' or one 'host'.
-- with_updates: run before and after update jobs (always available for a
-- manual check).
CREATE TABLE health_checks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    type            TEXT NOT NULL,
    target          TEXT NOT NULL DEFAULT '',
    expect          BIGINT NOT NULL DEFAULT 0,
    contains        TEXT NOT NULL DEFAULT '',
    insecure        BIGINT NOT NULL DEFAULT 0,
    cpu             BIGINT NOT NULL DEFAULT 0,
    memory          BIGINT NOT NULL DEFAULT 0,
    disk            BIGINT NOT NULL DEFAULT 0,
    paths           TEXT NOT NULL DEFAULT '[]',
    timeout_seconds BIGINT NOT NULL DEFAULT 10,
    scope           TEXT NOT NULL DEFAULT 'all',
    group_id        BIGINT REFERENCES host_groups(id) ON DELETE CASCADE DEFERRABLE,
    host_id         BIGINT REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    with_updates    BIGINT NOT NULL DEFAULT 1,
    enabled         BIGINT NOT NULL DEFAULT 1,
    created_at      BIGINT NOT NULL
);

-- Health check results per host: phase 'before'/'after' an update job,
-- 'check' for a manual or standalone run.
CREATE TABLE health_results (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id     BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    job_id      BIGINT NOT NULL DEFAULT 0,
    check_id    BIGINT NOT NULL DEFAULT 0,
    check_name  TEXT NOT NULL,
    check_type  TEXT NOT NULL,
    phase       TEXT NOT NULL,
    ok          BIGINT NOT NULL,
    value       TEXT NOT NULL DEFAULT '',
    message     TEXT NOT NULL DEFAULT '',
    duration_ms BIGINT NOT NULL DEFAULT 0,
    created_at  BIGINT NOT NULL
);
CREATE INDEX health_results_host ON health_results(host_id, created_at);
CREATE INDEX health_results_job ON health_results(job_id);
