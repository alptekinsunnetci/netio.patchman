-- netio.patchman PostgreSQL schema: the state of the SQLite migrations
-- 0001-0009 in one file (it records versions 1-9). Later schema changes add
-- a numbered file here and one in the SQLite directory.
--
-- All timestamps are UTC unix seconds (0 = never). Flags are 0/1 integers as
-- in SQLite, so queries and data transfer stay the same for both databases.
-- Foreign keys are DEFERRABLE so that a data transfer can insert tables in
-- any order (SET CONSTRAINTS ALL DEFERRED).

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               TEXT NOT NULL,
    name                TEXT NOT NULL,
    password_hash       TEXT NOT NULL,
    role                TEXT NOT NULL CHECK (role IN ('admin', 'operator', 'viewer')),
    disabled            BIGINT NOT NULL DEFAULT 0,
    created_at          BIGINT NOT NULL,
    last_login_at       BIGINT NOT NULL DEFAULT 0,
    password_changed_at BIGINT NOT NULL,
    totp_secret         TEXT NOT NULL DEFAULT '',
    totp_enabled_at     BIGINT NOT NULL DEFAULT 0,
    totp_last_step      BIGINT NOT NULL DEFAULT 0,
    locale              TEXT NOT NULL DEFAULT '',
    group_scoped        BIGINT NOT NULL DEFAULT 0
);
-- SQLite: email UNIQUE COLLATE NOCASE.
CREATE UNIQUE INDEX users_email_nocase ON users (lower(email));

CREATE TABLE sessions (
    token_hash   TEXT PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE,
    csrf_token   TEXT NOT NULL,
    created_at   BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL,
    ip           TEXT NOT NULL DEFAULT '',
    user_agent   TEXT NOT NULL DEFAULT ''
);
CREATE INDEX sessions_user ON sessions(user_id);

CREATE TABLE enrollment_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL,
    token_hash   TEXT NOT NULL UNIQUE,
    token_prefix TEXT NOT NULL,
    created_by   BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE,
    created_at   BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL DEFAULT 0,
    max_uses     BIGINT NOT NULL DEFAULT 0,
    uses         BIGINT NOT NULL DEFAULT 0,
    revoked_at   BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE hosts (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id            TEXT NOT NULL DEFAULT '',
    hostname              TEXT NOT NULL,
    fqdn                  TEXT NOT NULL DEFAULT '',
    os_id                 TEXT NOT NULL DEFAULT '',
    os_version_id         TEXT NOT NULL DEFAULT '',
    os_name               TEXT NOT NULL DEFAULT '',
    os_version            TEXT NOT NULL DEFAULT '',
    kernel                TEXT NOT NULL DEFAULT '',
    arch                  TEXT NOT NULL DEFAULT '',
    ip_addresses          TEXT NOT NULL DEFAULT '[]',
    package_manager       TEXT NOT NULL DEFAULT '',
    ecosystem             TEXT NOT NULL DEFAULT '',
    agent_version         TEXT NOT NULL DEFAULT '',
    remote_updates        BIGINT NOT NULL DEFAULT 0,
    reboot_required       BIGINT NOT NULL DEFAULT 0,
    uptime_seconds        BIGINT NOT NULL DEFAULT 0,
    agent_secret_hash     TEXT NOT NULL UNIQUE,
    enrolled_at           BIGINT NOT NULL,
    enrollment_token      BIGINT REFERENCES enrollment_tokens(id) ON DELETE SET NULL DEFERRABLE,
    last_seen_at          BIGINT NOT NULL DEFAULT 0,
    last_report_at        BIGINT NOT NULL DEFAULT 0,
    last_scan_at          BIGINT NOT NULL DEFAULT 0,
    needs_scan            BIGINT NOT NULL DEFAULT 0,
    report_errors         TEXT NOT NULL DEFAULT '[]',
    offline_notified      BIGINT NOT NULL DEFAULT 0,
    notes                 TEXT NOT NULL DEFAULT '',
    self_update           BIGINT NOT NULL DEFAULT 0,
    restart_services      TEXT NOT NULL DEFAULT '[]',
    virtualization        TEXT NOT NULL DEFAULT '',
    reboot_required_since BIGINT NOT NULL DEFAULT 0,
    upstream              TEXT NOT NULL DEFAULT '',
    kernel_patch          TEXT NOT NULL DEFAULT '',
    kernel_effective      TEXT NOT NULL DEFAULT '',
    livepatch_cves        TEXT NOT NULL DEFAULT '[]',
    exclude_packages      TEXT NOT NULL DEFAULT ''
);
CREATE INDEX hosts_machine ON hosts(machine_id);
CREATE INDEX hosts_needs_scan ON hosts(needs_scan);

CREATE TABLE host_packages (
    host_id        BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    name           TEXT NOT NULL,
    arch           TEXT NOT NULL DEFAULT '',
    version        TEXT NOT NULL,
    source_name    TEXT NOT NULL DEFAULT '',
    source_version TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (host_id, name, arch)
);
CREATE INDEX host_packages_name ON host_packages(name);

CREATE TABLE host_updates (
    host_id           BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    name              TEXT NOT NULL,
    current_version   TEXT NOT NULL DEFAULT '',
    available_version TEXT NOT NULL,
    repository        TEXT NOT NULL DEFAULT '',
    security          BIGINT NOT NULL DEFAULT 0,
    title             TEXT NOT NULL DEFAULT '',
    severity          TEXT NOT NULL DEFAULT '',
    cves              TEXT NOT NULL DEFAULT '[]',
    PRIMARY KEY (host_id, name)
);
CREATE INDEX host_updates_name ON host_updates(name);

-- Cached OSV query results per (ecosystem, package, version).
CREATE TABLE osv_queries (
    ecosystem  TEXT NOT NULL,
    name       TEXT NOT NULL,
    version    TEXT NOT NULL,
    record_ids TEXT NOT NULL,
    checked_at BIGINT NOT NULL,
    PRIMARY KEY (ecosystem, name, version)
);

-- Cached OSV records: gzip-compressed JSON (plain JSON from old versions).
CREATE TABLE osv_records (
    id         TEXT PRIMARY KEY,
    modified   TEXT NOT NULL,
    fetched_at BIGINT NOT NULL,
    data       BYTEA NOT NULL
);

-- Vulnerability text fields are stored verbatim from the source.
CREATE TABLE vulnerabilities (
    cve_id           TEXT PRIMARY KEY,
    title            TEXT NOT NULL DEFAULT '',
    description      TEXT NOT NULL DEFAULT '',
    description_lang TEXT NOT NULL DEFAULT 'en',
    cvss_score       DOUBLE PRECISION,
    cvss_vector      TEXT NOT NULL DEFAULT '',
    cvss_version     TEXT NOT NULL DEFAULT '',
    severity         TEXT NOT NULL DEFAULT 'unknown',
    published_at     BIGINT NOT NULL DEFAULT 0,
    modified_at      BIGINT NOT NULL DEFAULT 0,
    fetched_at       BIGINT NOT NULL DEFAULT 0,
    source           TEXT NOT NULL DEFAULT '',
    refs             TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX vulnerabilities_severity ON vulnerabilities(severity);

-- CISA Known Exploited Vulnerabilities catalog, values verbatim.
CREATE TABLE kev (
    cve_id     TEXT PRIMARY KEY,
    date_added TEXT NOT NULL DEFAULT '',
    due_date   TEXT NOT NULL DEFAULT '',
    ransomware TEXT NOT NULL DEFAULT ''
);

CREATE TABLE advisories (
    id     TEXT PRIMARY KEY,
    title  TEXT NOT NULL DEFAULT '',
    url    TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL DEFAULT ''
);

CREATE TABLE vulnerability_advisories (
    cve_id      TEXT NOT NULL,
    advisory_id TEXT NOT NULL,
    PRIMARY KEY (cve_id, advisory_id)
);

CREATE TABLE findings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id           BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    cve_id            TEXT NOT NULL,
    package_name      TEXT NOT NULL,
    installed_version TEXT NOT NULL,
    fixed_version     TEXT NOT NULL DEFAULT '',
    record_id         TEXT NOT NULL DEFAULT '',
    status            TEXT NOT NULL DEFAULT 'open',
    status_note       TEXT NOT NULL DEFAULT '',
    status_changed_by BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE,
    first_detected_at BIGINT NOT NULL,
    last_checked_at   BIGINT NOT NULL,
    resolved_at       BIGINT NOT NULL DEFAULT 0,
    notified          BIGINT NOT NULL DEFAULT 0,
    status_expires_at BIGINT NOT NULL DEFAULT 0,
    sla_notified_at   BIGINT NOT NULL DEFAULT 0,
    UNIQUE (host_id, cve_id, package_name)
);
CREATE INDEX findings_cve ON findings(cve_id);
CREATE INDEX findings_status ON findings(status);
CREATE INDEX findings_status_expires ON findings(status, status_expires_at);

-- Host groups (names unique ignoring case; SQLite: UNIQUE COLLATE NOCASE).
CREATE TABLE host_groups (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             TEXT NOT NULL,
    description      TEXT NOT NULL DEFAULT '',
    created_at       BIGINT NOT NULL,
    exclude_packages TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX host_groups_name_nocase ON host_groups (lower(name));

CREATE TABLE host_group_members (
    group_id BIGINT NOT NULL REFERENCES host_groups(id) ON DELETE CASCADE DEFERRABLE,
    host_id  BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    PRIMARY KEY (group_id, host_id)
);
CREATE INDEX host_group_members_host ON host_group_members(host_id);

-- Scheduled update rules (maintenance windows). days is a weekday bitmask
-- (bit 0 = Sunday); minute is minutes after midnight in the display zone.
CREATE TABLE schedules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    enabled        BIGINT NOT NULL DEFAULT 1,
    job_type       TEXT NOT NULL,
    days           BIGINT NOT NULL,
    minute         BIGINT NOT NULL,
    window_minutes BIGINT NOT NULL,
    target         TEXT NOT NULL CHECK (target IN ('all', 'os', 'hosts')),
    os_id          TEXT NOT NULL DEFAULT '',
    next_run_at    BIGINT NOT NULL DEFAULT 0,
    last_run_at    BIGINT NOT NULL DEFAULT 0,
    last_queued    BIGINT NOT NULL DEFAULT 0,
    last_skipped   BIGINT NOT NULL DEFAULT 0,
    created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE,
    created_at     BIGINT NOT NULL,
    updated_at     BIGINT NOT NULL,
    group_id       BIGINT REFERENCES host_groups(id) ON DELETE SET NULL DEFERRABLE,
    reboot         BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX schedules_due ON schedules(enabled, next_run_at);

CREATE TABLE schedule_hosts (
    schedule_id BIGINT NOT NULL REFERENCES schedules(id) ON DELETE CASCADE DEFERRABLE,
    host_id     BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    PRIMARY KEY (schedule_id, host_id)
);

CREATE TABLE jobs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id       BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE DEFERRABLE,
    type          TEXT NOT NULL,
    packages      TEXT NOT NULL DEFAULT '[]',
    status        TEXT NOT NULL DEFAULT 'queued',
    created_by    BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE,
    created_at    BIGINT NOT NULL,
    dispatched_at BIGINT NOT NULL DEFAULT 0,
    finished_at   BIGINT NOT NULL DEFAULT 0,
    exit_code     BIGINT NOT NULL DEFAULT 0,
    output        TEXT NOT NULL DEFAULT '',
    params        TEXT NOT NULL DEFAULT '{}',
    schedule_id   BIGINT REFERENCES schedules(id) ON DELETE SET NULL DEFERRABLE,
    expires_at    BIGINT NOT NULL DEFAULT 0,
    remaining     TEXT NOT NULL DEFAULT '[]',
    reboot_job_id BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX jobs_host_status ON jobs(host_id, status);
CREATE INDEX jobs_type_status ON jobs(type, status);
CREATE INDEX jobs_status_expires ON jobs(status, expires_at);

-- In-app notifications, rendered from (kind, params) at display time.
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at BIGINT NOT NULL,
    level      TEXT NOT NULL,
    kind       TEXT NOT NULL,
    params     TEXT NOT NULL DEFAULT '{}',
    link       TEXT NOT NULL DEFAULT '',
    read_at    BIGINT NOT NULL DEFAULT 0,
    host_id    BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX notifications_read ON notifications(read_at);

CREATE TABLE settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         BIGINT NOT NULL,
    user_id    BIGINT,
    user_email TEXT NOT NULL DEFAULT '',
    action     TEXT NOT NULL,
    target     TEXT NOT NULL DEFAULT '',
    details    TEXT NOT NULL DEFAULT '',
    ip         TEXT NOT NULL DEFAULT ''
);
CREATE INDEX audit_log_at ON audit_log(at);

-- TOTP recovery codes (SHA-256 hashes).
CREATE TABLE user_recovery_codes (
    user_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE,
    code_hash TEXT NOT NULL,
    PRIMARY KEY (user_id, code_hash)
);

-- One row per UTC day with the fleet state at the last snapshot of that day.
CREATE TABLE daily_snapshots (
    day              BIGINT PRIMARY KEY,
    hosts            BIGINT NOT NULL,
    critical         BIGINT NOT NULL,
    high             BIGINT NOT NULL,
    medium           BIGINT NOT NULL,
    low              BIGINT NOT NULL,
    other            BIGINT NOT NULL,
    kev              BIGINT NOT NULL,
    open_findings    BIGINT NOT NULL,
    security_updates BIGINT NOT NULL,
    reboot_required  BIGINT NOT NULL,
    taken_at         BIGINT NOT NULL
);

-- Slack, Microsoft Teams, Telegram or a generic JSON webhook.
CREATE TABLE notify_channels (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    type          TEXT NOT NULL CHECK (type IN ('slack', 'teams', 'telegram', 'webhook')),
    url           TEXT NOT NULL,
    secret        TEXT NOT NULL DEFAULT '',
    chat_id       TEXT NOT NULL DEFAULT '',
    min_level     TEXT NOT NULL DEFAULT 'warning' CHECK (min_level IN ('info', 'warning', 'critical')),
    enabled       BIGINT NOT NULL DEFAULT 1,
    created_at    BIGINT NOT NULL,
    last_sent_at  BIGINT NOT NULL DEFAULT 0,
    last_error    TEXT NOT NULL DEFAULT '',
    last_error_at BIGINT NOT NULL DEFAULT 0
);

-- Microsoft Security Update Guide lookups by KB number (JSON).
CREATE TABLE msrc_kb_cache (
    kb         TEXT PRIMARY KEY,
    data       TEXT NOT NULL,
    fetched_at BIGINT NOT NULL
);

-- EPSS (FIRST.org): probability of exploitation in the next 30 days.
CREATE TABLE epss (
    cve_id     TEXT PRIMARY KEY,
    score      DOUBLE PRECISION NOT NULL,
    percentile DOUBLE PRECISION NOT NULL
);

-- Operators and viewers limited to the hosts of some groups.
CREATE TABLE user_groups (
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE,
    group_id BIGINT NOT NULL REFERENCES host_groups(id) ON DELETE CASCADE DEFERRABLE,
    PRIMARY KEY (user_id, group_id)
);

-- API tokens act as their user. Only the SHA-256 hash is stored.
CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE,
    name         TEXT NOT NULL,
    token_hash   TEXT NOT NULL UNIQUE,
    prefix       TEXT NOT NULL,
    read_only    BIGINT NOT NULL DEFAULT 1,
    created_at   BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL DEFAULT 0,
    last_used_at BIGINT NOT NULL DEFAULT 0,
    revoked_at   BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX api_tokens_user ON api_tokens(user_id);
