-- Ticket systems and Zabbix are new channel types: the type CHECK goes away
-- (store.ValidChannelType checks it). Event filter of a channel (JSON array
-- of event ids, empty = every event at or above min_level) and type-specific
-- settings (JSON: Jira project, ServiceNow table, GLPI app token, Zabbix host and key).
ALTER TABLE notify_channels DROP CONSTRAINT IF EXISTS notify_channels_type_check;
ALTER TABLE notify_channels ADD COLUMN events TEXT NOT NULL DEFAULT '[]';
ALTER TABLE notify_channels ADD COLUMN config TEXT NOT NULL DEFAULT '{}';

-- Delivery history: one row per notification and channel, with the
-- notification itself so a failed delivery can be sent again.
CREATE TABLE channel_deliveries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id  BIGINT NOT NULL REFERENCES notify_channels(id) ON DELETE CASCADE DEFERRABLE,
    event       TEXT NOT NULL,
    kind        TEXT NOT NULL,
    ok          BIGINT NOT NULL,
    attempts    BIGINT NOT NULL,
    error       TEXT NOT NULL DEFAULT '',
    duration_ms BIGINT NOT NULL DEFAULT 0,
    payload     TEXT NOT NULL,
    created_at  BIGINT NOT NULL
);
CREATE INDEX channel_deliveries_channel ON channel_deliveries(channel_id, created_at);
